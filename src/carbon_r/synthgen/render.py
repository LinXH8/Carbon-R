"""HTML layout -> PDF for synthetic documents.

Two rules hold here:

1. **No arithmetic in the template.** Every figure arrives as a pre-formatted string in
   `bill_context()`, derived from an already-validated ElectricityBill. The page can only
   print numbers that passed the model validator.
2. **No hand-written dates in the template.** Every date is formatted from the model's
   period_start / period_end / bill_date, which come from `calendar.monthrange` and so can
   never name a day their month does not have. A literal date in a layout is an
   unvalidated number on a document whose whole job is to be trustworthy.

WeasyPrint is imported lazily, inside `write_pdf`, so the test suite can render and compare
HTML without needing pango/cairo present. On macOS with Homebrew, WeasyPrint needs
`DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib` - anaconda shadows the brew libraries on the
dyld search path. The Makefile's `docs` target exports it.
"""

from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined, select_autoescape

from carbon_r.models.electricity_bill import ElectricityBill

TEMPLATES_DIR = Path(__file__).parent / "templates"
DEFAULT_TEMPLATE = "electricity_bill_a.html.j2"

# Wording fixed by SYNTHGEN_SPEC.md 1.7; identical on every document kind.
SYNTHETIC_NOTICE = (
    "SYNTHETIC DOCUMENT - generated by Carbon R synthgen for testing. Not a real document. "
    "All parties and figures are fictional."
)


def environment() -> Environment:
    return Environment(
        loader=FileSystemLoader(TEMPLATES_DIR),
        autoescape=select_autoescape(["html", "xml"]),
        undefined=StrictUndefined,  # a missing field must fail loudly, not render blank
        trim_blocks=True,
        lstrip_blocks=True,
    )


def _date(value) -> str:
    return value.strftime("%d %b %Y")


def _money(value) -> str:
    return f"{value:,.2f}"


def bill_context(bill: ElectricityBill) -> dict:
    """Pre-format every value the layout prints. All strings; no numbers to manipulate."""
    from carbon_r.synthgen.profiles import VENDOR_ADDRESS, VENDOR_SUPPORT

    return {
        "notice": SYNTHETIC_NOTICE,
        "doc_id": bill.doc_id,
        "layout_id": bill.layout_id,
        "vendor_name": bill.vendor_name,
        "vendor_uen": bill.vendor_uen,
        "vendor_address": VENDOR_ADDRESS,
        "vendor_support": VENDOR_SUPPORT,
        "customer_name": bill.customer_name,
        "customer_address": bill.customer_address,
        "account_number": bill.account_number,
        "document_date": _date(bill.document_date),
        "period_start": _date(bill.period_start),
        "period_end": _date(bill.period_end),
        "days_in_period": f"{bill.days_in_period}",
        "meter_number": bill.meter_number,
        "previous_reading": f"{bill.previous_reading_kwh:,}",
        "current_reading": f"{bill.current_reading_kwh:,}",
        "consumption": f"{bill.consumption_kwh:,}",
        "reading_basis": "Estimated" if bill.is_estimated_reading else "Actual",
        "tariff_plan_code": bill.tariff_plan_code,
        "tariff_plan_name": bill.tariff_plan_name,
        "tension": bill.tension,
        "currency": bill.currency,
        "tariff_cents_per_kwh": f"{bill.tariff_cents_per_kwh:.2f}",
        "energy_charge": _money(bill.energy_charge_sgd),
        "fixed_charge": _money(bill.fixed_charge_sgd),
        "subtotal": _money(bill.subtotal_sgd),
        "gst_percent": f"{bill.gst_rate * 100:.0f}",
        "gst_amount": _money(bill.gst_amount_sgd),
        "total": _money(bill.total_sgd),
        "generator_version": bill.generator_version,
        "generator_seed": f"{bill.generator_seed}",
    }


def template_for(bill: ElectricityBill) -> str:
    """Templates are named <doc_kind>_<layout letter>.html.j2 (spec 3.1)."""
    return f"{bill.doc_kind}_{bill.layout_id.rsplit('_', 1)[-1]}.html.j2"


def render_html(bill: ElectricityBill, template_name: str | None = None) -> str:
    name = template_name or template_for(bill)
    return environment().get_template(name).render(**bill_context(bill))


def write_pdf(html: str, path: Path) -> int:
    """Render HTML to a PDF file. Returns bytes written.

    WeasyPrint is imported here rather than at module scope so that importing this module
    (and running the HTML-level determinism tests) does not require the native libraries.
    """
    from weasyprint import HTML

    pdf = HTML(string=html).write_pdf()
    path.write_bytes(pdf)
    return len(pdf)
